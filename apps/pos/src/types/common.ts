/**
 * 表單輸入與資料模型的 id／金額欄位型別。
 *
 * 這個聯合型別誠實反映現行程式碼的實際行為，不是理想型別：後台管理頁的
 * `<input v-model="...">` 一律綁成字串（Vue 3 的 v-model 對 `type="number"`
 * 不會自動轉型，需顯式加上 `.number` 修飾符，而現行程式碼並未加上），
 * 但這些欄位在種子資料中是 number。新增或編輯後，同一個陣列裡因此會同時
 * 存在字串與數字的 id／價格。
 *
 * 這是型別遷移過程中新發現、原本 18 項缺陷目錄未收錄的問題（暫記為
 * D-19：表單輸入與資料模型型別不一致）。P0 階段只如實標記型別、不改變
 * 行為；修正應在 P1 隨計價／目錄領域模型一併處理（改為送出當下正規化
 * 成 number，或改用字串 id 並移除大小比較）。
 */
export type FormNumeric = number | string

/**
 * 後台管理頁「目前選取列」的既有慣例：`ref({})` 起始（尚未選取任何一列），
 * 使用者從 `el-table` 選取後才被指派成完整的列物件，並以
 * `if (current.value.name)` 之類的真值檢查判斷是否已選取。
 *
 * 用 `Partial<T>` 如實描述這個「空物件當作尚未選取」的既有慣例——P0 不
 * 引入 `null`／`undefined` 之類的正式空值型別，避免變動任何判斷式的行為。
 */
export type MaybeSelected<T> = Partial<T>
